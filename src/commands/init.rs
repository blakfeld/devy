/// How `devy init` produces its config.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    /// The default: offline detection, then Claude. With `show_context`, print the
    /// request instead of sending it.
    Ai { show_context: bool },
    /// Offline detection only.
    Detect,
}

/// How AI `init` reviews executable entries with the user, injected so tests never
/// touch the real terminal.
pub(crate) struct Review<'a> {
    /// stdin and stderr are both terminals, so the user can be asked.
    pub interactive: bool,
    pub input: &'a mut dyn BufRead,
    /// Where the listing and the prompt go (stderr in a real run).
    pub out: &'a mut dyn Write,
}

#[cfg_attr(test, mutants::skip)] // binds the real claude lookup and terminal; logic is in run_with
pub fn run(mode: Mode, force: bool, config_path: &Path) -> Result<()> {
    let interactive = std::io::stdin().is_terminal() && std::io::stderr().is_terminal();
    let stdin = std::io::stdin();
    let mut input = stdin.lock();
    let mut out = std::io::stderr();
    run_with(
        mode,
        force,
        config_path,
        ai::Client::from_env,
        Review {
            interactive,
            input: &mut input,
            out: &mut out,
        },
    )
}

/// `run` with the client lookup injected, so tests never run the real `claude`.
fn run_with(
    mode: Mode,
    force: bool,
    config_path: &Path,
    client: impl FnOnce() -> Result<ai::Client>,
    review: Review<'_>,
) -> Result<()> {
    // Checked before scanning the project or looking for claude.
    if config_path.exists() && !force {
        bail!("devy.yml already exists. Use {} to overwrite.", "--force");
    }

    let dir = project_dir(config_path);
    match mode {
        Mode::Detect => {
            let body = init_detect::detect(&dir).render(DETECT_HEADER);
            crate::fs_safe::write_atomic(config_path, body.as_bytes(), 0o644)?;
            output::success(&format!("wrote {}", config_path.display()));
            agent_setup::run_for_init(&dir);
            Ok(())
        }
        Mode::Ai { show_context: true } => {
            let preview =
                init_prompt::request(&dir, ai::model_from_env().as_deref()).render_preview();
            print!("{}", output::clean(&preview));
            Ok(())
        }
        Mode::Ai {
            show_context: false,
        } => {
            let client = client()
                .map_err(|e| anyhow!("{e} — or run `devy init --detect` to draft one offline"))?;
            run_ai(&client, &dir, config_path, review)?;
            agent_setup::run_for_init(&dir);
            Ok(())
        }
    }
}

fn ai_header(model: &str) -> String {
    format!(
        "# Generated by devy init ({}) — AI-generated, review before committing",
        init_detect::snippet(model)
    )
}

/// Asks the model for a config, validates it, repairs it at most once, has the user
/// review any entries that run commands, and writes it.
fn run_ai(client: &ai::Client, dir: &Path, config_path: &Path, review: Review<'_>) -> Result<()> {
    output::step(&format!(
        "Drafting devy.yml with claude{}",
        client
            .model
            .as_deref()
            .map(|m| format!(" ({m})"))
            .unwrap_or_default()
    ));
    let request = init_prompt::request(dir, client.model.as_deref());
    let mut reply = client.complete(&request)?;
    let mut yaml = extract_yaml(&reply.text);
    let mut errors = validate(&yaml);
    if !errors.is_empty() {
        output::step("The draft failed validation; asking for a fix");
        let repair = request.follow_up(&reply.text, repair_prompt(&errors));
        reply = client.complete(&repair)?;
        yaml = extract_yaml(&reply.text);
        errors = validate(&yaml);
    }
    if !errors.is_empty() {
        for error in &errors {
            output::warn(error);
        }
        bail!(
            "the AI-generated devy.yml is still invalid, so nothing was written — \
             run `devy init --detect` to draft one offline"
        );
    }

    // Name the model claude actually used; fall back to what was requested.
    let model = reply
        .model
        .or_else(|| client.model.clone())
        .unwrap_or_else(|| "claude".to_string());
    let config: DevyConfig = crate::yaml_safe::from_str_strict(&yaml, "the generated devy.yml")?;
    let summary = config_diff::summary(&config, dir);

    // Every entry is shown, including implicit setup steps; only a terminal user can
    // keep them. A config that only installs the packages its dependencies imply has
    // nothing to review here.
    let mut keep = summary
        .iter()
        .all(|e| e.group == Group::SystemPackages && implied_by_dependency(e));
    if !keep {
        let mut listing = String::from("\nCommands this config would run:\n");
        for line in config_diff::render_summary(&summary) {
            listing.push_str(&format!("  {line}\n"));
        }
        if review.interactive {
            listing.push_str(&format!(
                "\ndevy up will run them in {}.\nKeep these entries? [y/N] ",
                output::clean_line(
                    &std::fs::canonicalize(dir)
                        .unwrap_or_else(|_| dir.to_path_buf())
                        .display()
                        .to_string()
                )
            ));
        }
        review
            .out
            .write_all(listing.as_bytes())
            .and_then(|()| review.out.flush())
            .context("Failed to write the review prompt")?;
        if review.interactive {
            let mut answer = String::new();
            review
                .input
                .read_line(&mut answer)
                .context("Failed to read the answer")?;
            keep = matches!(answer.trim().to_ascii_lowercase().as_str(), "y" | "yes");
        }
    }

    // Implicit setup steps alone leave nothing to strip: keep the reply (and its comments).
    let nothing_to_strip = !has_config_setup(&config) && summary.iter().all(implied_by_dependency);
    let (yaml, config, removed) = if keep || nothing_to_strip {
        (yaml, config, Vec::new())
    } else {
        let stripped = strip_executable(&yaml)?;
        if let Some(issue) = validate(&stripped).into_iter().next() {
            bail!(
                "removing the suggested commands left an invalid devy.yml ({issue}), so nothing was written"
            );
        }
        let config: DevyConfig =
            crate::yaml_safe::from_str_strict(&stripped, "the generated devy.yml")?;
        let left = config_diff::summary(&config, dir);
        // Fail closed: what survives may only be setup steps implied by a dependency and
        // the project's own files, never anything the config itself spells out.
        if !left.iter().all(implied_by_dependency) || has_config_setup(&config) {
            bail!(
                "could not remove the suggested commands from the AI-generated devy.yml, so nothing was written"
            );
        }
        let removed: Vec<ExecEntry> = summary
            .iter()
            .filter(|e| !left.contains(e))
            .cloned()
            .collect();
        let todos: String = removed.iter().map(|e| todo_line(e) + "\n").collect();
        (format!("{todos}{stripped}"), config, removed)
    };
    let body = format!("{}\n{yaml}", ai_header(&model));
    crate::fs_safe::write_atomic(config_path, body.as_bytes(), 0o644)?;
    for dep in config.normalized_dependencies()? {
        for warning in modules::get(&dep.name).config_warnings(&dep) {
            output::warn(&format!("{}: {}", dep.name, warning));
        }
    }
    output::success(&format!("wrote {}", config_path.display()));
    if !keep && removed.len() < summary.len() {
        output::info(
            "packages and setup steps implied by the dependencies and project files were kept — devy up will run them",
        );
    }
    if !removed.is_empty() {
        output::warn(&format!(
            "left out {} suggested {} that would run commands; see the `# TODO: review suggested` comments in devy.yml",
            removed.len(),
            if removed.len() == 1 {
                "entry"
            } else {
                "entries"
            }
        ));
    }
    Ok(())
}

/// Entries that follow from a dependency being listed (its package, and the setup steps
/// its module derives from the project's files) rather than from a field the config
/// spells out, so stripping executable fields leaves them.
fn implied_by_dependency(entry: &ExecEntry) -> bool {
    match entry.group {
        Group::ProjectSetup => true,
        // Not the entry naming dependencies that fail to normalize.
        Group::SystemPackages => entry.key.ends_with(".package"),
        _ => false,
    }
}

/// Whether a dependency of `config` spells out a setup step itself (`global_packages`),
/// rather than one following from the module and the project's files.
fn has_config_setup(config: &DevyConfig) -> bool {
    config
        .normalized_dependencies()
        .unwrap_or_default()
        .iter()
        .any(|d| EXEC_EXTRA_KEYS.iter().any(|k| d.extra.contains_key(*k)))
}

/// The `# TODO:` line for an entry removed from the generated file: its field (without a
/// list index) and value, sanitized and cut as detected-init TODOs are, so it is exactly
/// one comment line.
fn todo_line(entry: &ExecEntry) -> String {
    let field = match entry.key.rsplit_once('[') {
        Some((field, idx)) if idx.ends_with(']') => field,
        _ => entry.key.as_str(),
    };
    // A config-spelled setup step is restored through the key that produced it.
    let field = match field.strip_suffix(".setup") {
        Some(dep) if entry.value.ends_with(crate::modules::GLOBAL_PACKAGES_STEP) => {
            format!("{dep}.global_packages")
        }
        _ => field.to_string(),
    };
    format!(
        "# TODO: review suggested {} — {}",
        init_detect::snippet(&field),
        init_detect::snippet(&entry.value)
    )
}

/// Dependency keys that make devy run something or fetch from somewhere else. `shell`
/// only selects the interpreter for `after_install` and goes with it; `global_packages`
/// become an `npm install -g` setup step.
const EXEC_DEP_KEYS: &[&str] = &[
    "after_install",
    "shell",
    "install_cmd",
    "tap",
    "image",
    "global_packages",
];

/// Module keys in [`EXEC_DEP_KEYS`] whose values become setup steps (`npm install -g`).
const EXEC_EXTRA_KEYS: &[&str] = &["install_cmd", "global_packages"];

/// `yaml` without any executable field: `hooks` and `environment` (every key is
/// execution-affecting, see `config_diff`) and the executable keys of every dependency.
/// A dependency left with no keys becomes a bare name. Comments are not kept.
fn strip_executable(yaml: &str) -> Result<String> {
    crate::yaml_safe::check(
        yaml,
        "the generated devy.yml",
        crate::yaml_safe::Aliases::Reject,
    )?;
    let mut doc: yaml::Value =
        yaml::from_str(yaml).context("the generated devy.yml does not parse")?;
    let Some(root) = doc.as_mapping_mut() else {
        bail!("the generated devy.yml is not a mapping");
    };
    root.shift_remove("hooks");
    root.shift_remove("environment");
    if let Some(deps) = root
        .get_mut("dependencies")
        .and_then(|d| d.as_sequence_mut())
    {
        for dep in deps.iter_mut() {
            let Some(map) = dep.as_mapping_mut() else {
                continue;
            };
            let mut bare = None;
            for (name, cfg) in map.iter_mut() {
                if let Some(cfg) = cfg.as_mapping_mut() {
                    for key in EXEC_DEP_KEYS {
                        cfg.shift_remove(*key);
                    }
                    if cfg.is_empty() {
                        bare = Some(name.clone());
                    }
                }
            }
            if let (Some(name), 1) = (bare, map.len()) {
                *dep = name;
            }
        }
    }
    Ok(yaml::to_string(&doc)?)
}

/// The YAML in the first fenced `yaml` block of `reply`, or the whole reply.
fn extract_yaml(reply: &str) -> String {
    // CRLF line endings are harmless; a stray CR is caught by `validate`.
    let reply = &reply.replace("\r\n", "\n");
    let fenced = ["```yaml", "```yml"].iter().find_map(|fence| {
        let start = reply.find(fence)?;
        let body = &reply[start + fence.len()..];
        let body = &body[body.find('\n')? + 1..];
        Some(body.find("```").map_or(body, |end| &body[..end]))
    });
    let mut yaml = fenced.unwrap_or(reply).trim().to_string();
    yaml.push('\n');
    yaml
}

/// Problems that keep `yaml` from being written: parse errors and static config issues.
fn validate(yaml: &str) -> Vec<String> {
    let config: DevyConfig = match crate::yaml_safe::from_str_strict(yaml, "devy.yml") {
        Ok(config) => config,
        Err(e) => return vec![format!("devy.yml does not parse: {e}")],
    };
    let mut issues = static_issues(&config).unwrap_or_else(|e| vec![format!("{e:#}")]);
    // What the user reviews must be exactly what is written.
    if output::clean(yaml) != yaml {
        issues.push(
            "devy.yml contains control or invisible characters (escape sequences, bidi overrides, zero-width text); remove them".to_string(),
        );
    }
    issues
}

fn repair_prompt(errors: &[String]) -> String {
    let list: String = errors.iter().map(|e| format!("- {e}\n")).collect();
    format!(
        "devy rejected that devy.yml:\n{list}\nReply with the corrected, complete devy.yml in a single ```yaml fenced block."
    )
}

/// The directory `config_path` lives in; `init` never looks above it.
fn project_dir(config_path: &Path) -> PathBuf {
    match config_path.parent() {
        Some(p) if !p.as_os_str().is_empty() => p.to_path_buf(),
        _ => PathBuf::from("."),
    }
}

