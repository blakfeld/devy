    #[test]
    fn every_executable_field_is_stripped_into_todos() {
        let reply = concat!(
            "name: shop\n",
            "dependencies:\n",
            "  - redis:\n      image: \"evil/redis\"\n      port: 6380\n",
            "  - jq:\n      after_install: \"echo hi\"\n      shell: bash\n",
            "  - foo:\n      tap: org/tap\n      version: \"1.2\"\n",
            "  - node:\n      version: \"22\"\n",
            "environment:\n  NODE_OPTIONS: \"--require ./x.js\"\n",
            "hooks:\n  before_up: [\"a\", \"b\"]\n",
            "commands:\n  dev: \"npm run dev\"\n",
        );
        let (result, written, _, _) = review_run(&[reply], false, "");
        result.unwrap();
        let written = written.unwrap();
        let config: DevyConfig = crate::yaml_safe::from_str_strict(&written, "t").unwrap();
        let (_tmp, dir) = tmp_config();
        let left: Vec<_> = config_diff::summary(&config, dir.parent().unwrap());
        // Only the packages the dependencies install remain.
        assert!(
            left.iter().all(|e| e.group == Group::SystemPackages),
            "{left:?}\n{written}"
        );
        assert_eq!(left.len(), 4, "{left:?}");
        // Commands are not part of the review, and plain keys survive.
        assert_eq!(config.commands.len(), 1);
        let deps = config.normalized_dependencies().unwrap();
        assert_eq!(
            deps[0].extra.get("port").and_then(|v| v.as_u64()),
            Some(6380)
        );
        assert_eq!(deps[1].name, "jq");
        assert_eq!(deps[2].version.as_deref(), Some("1.2"));
        assert_eq!(deps[3].version.as_deref(), Some("22"));
        for todo in [
            "# TODO: review suggested hooks.before_up — before_up: a\n",
            "# TODO: review suggested hooks.before_up — before_up: b\n",
            "# TODO: review suggested dependencies.jq.after_install — jq after_install: echo hi (shell: bash)\n",
            "# TODO: review suggested dependencies.foo.tap — foo tap: org/tap\n",
            "# TODO: review suggested dependencies.redis.image — redis image: evil/redis\n",
            "# TODO: review suggested environment.NODE_OPTIONS — NODE_OPTIONS=--require ./x.js\n",
        ] {
            assert!(written.contains(todo), "{todo}\n{written}");
        }
    }

